"""Build the quality-inspection detector (weights/qc-yoloe.pt) and its vocabulary.

Ultralytics YOLOE can be prompted with text or with example boxes. This script reads
weights/references/references.json and gives the model one output class per prompt:

- text prompts per product ("stainless steel water bottle", "mobile phone charger", ...),
- one visual-prompt class per reference photo (boxes drawn on photos of real items),
- background prompts (person, face, hand, door, ...) that the service ignores,
- other-object prompts (cup, book, keys, scissors, ...) that absorb everyday items so they
  are not forced into a product class; the service reports them as "out_of_range".

Every product class is mapped back to its product key in weights/vocabulary.json and the
other objects are listed under "other_objects"; the service drops everything else. Text prompts need the CLIP tokenizer, which tools.clip_shim
provides from the open_clip_torch package (PyPI). No training run is involved.

Usage (from inference/):
    .venv/Scripts/python -m tools.build_qc_model            # Windows
    .venv/bin/python -m tools.build_qc_model                 # macOS / Linux
Then restart the inference service.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F

ROOT = Path(__file__).resolve().parent.parent
REFS = ROOT / "weights" / "references"
TARGET = ROOT / "weights" / "qc-yoloe.pt"
VOCAB = ROOT / "weights" / "vocabulary.json"


def visual_embeddings(model, spec: dict) -> list[tuple[str, str, torch.Tensor]]:
    """One embedding per reference photo (not averaged, so distinct shapes stay distinct)."""
    from ultralytics.models.yolo.yoloe import YOLOEVPSegPredictor

    found: list[tuple[str, str, torch.Tensor]] = []
    for ref in spec.get("references", []):
        predictor = YOLOEVPSegPredictor(overrides={"task": "segment", "mode": "predict", "save": False, "batch": 1, "verbose": False})
        boxes = np.array(ref["boxes"], dtype=np.float32)
        predictor.set_prompts({"bboxes": boxes, "cls": np.zeros(len(boxes), dtype=np.int64)})
        predictor.setup_model(model=model.model, verbose=False)
        predictor.model.names = {0: "object0"}
        vpe = predictor.get_vpe(str(REFS / ref["image"]))  # (1, 1, D)
        found.append((ref["class"], Path(ref["image"]).stem, F.normalize(vpe[0, 0].detach().float().cpu(), dim=-1)))
        print(f"  reference {ref['image']} -> {ref['class']}")
    return found


def main() -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", default="yoloe-11l-seg.pt", help="YOLOE base weights in weights/ (11l default and most accurate; 11s is about 4x faster)")
    ap.add_argument("--out", default=str(TARGET), help="output .pt path")
    args = ap.parse_args()
    base = ROOT / "weights" / args.base
    target = Path(args.out)
    os.environ.setdefault("YOLO_AUTOINSTALL", "false")
    from tools.clip_shim import install

    install()
    from ultralytics import YOLOE

    if not base.is_file():
        print(f"Missing {base}. Download it once with: python -c \"from ultralytics import YOLOE; YOLOE('{args.base}')\" and move it to weights/.")
        return 1
    spec = json.loads((REFS / "references.json").read_text(encoding="utf-8"))
    model = YOLOE(str(base))

    names: list[str] = []
    owners: dict[str, str] = {}
    embeds: list[torch.Tensor] = []

    prompts = [(cls, text) for cls, texts in spec.get("prompts", {}).items() for text in texts]
    background = list(spec.get("background", []))
    others = list(spec.get("other_objects", []))
    texts = [t for _, t in prompts] + background + others
    if texts:
        tpe = model.get_text_pe(texts)[0].detach().float().cpu()  # (N, D)
        for i, text in enumerate(texts):
            names.append(text)
            embeds.append(tpe[i])
        for cls, text in prompts:
            owners[text] = cls

    for cls, stem, emb in visual_embeddings(model, spec):
        name = f"{cls} (ref: {stem})"
        names.append(name)
        owners[name] = cls
        embeds.append(emb)

    model.set_classes(names, torch.stack(embeds)[None])
    model.save(str(target))

    vocab = {
        "_comment": "Generated by tools/build_qc_model.py: model class name -> product key. 'other_objects' are reported as out_of_range; classes not listed (background) are dropped by the service.",
        "classes": {},
        "other_objects": others,
    }
    for cls in spec["classes"]:
        vocab["classes"][cls] = [n for n, owner in owners.items() if owner == cls]
    VOCAB.write_text(json.dumps(vocab, indent=2) + "\n", encoding="utf-8")
    print(
        f"Saved {target.name} (base {args.base}): {len(names)} classes "
        f"({len(owners)} product, {len(others)} other-object, {len(background)} background); wrote {VOCAB.name}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
